using System.Text.Json;
using System.Text.Json.Serialization;

namespace PulseDesk.Agent;

// The published agent is trimmed to keep the employee download small. Reflection-based JSON
// cannot see these types after trimming, so use a source-generated context everywhere.
[JsonSourceGenerationOptions(WriteIndented = true)]
[JsonSerializable(typeof(Settings))]
[JsonSerializable(typeof(EmbeddedConfig.Conf))]
internal partial class AgentJsonContext : JsonSerializerContext { }

public sealed class Settings
{
    public string Server { get; set; } = "";
    public string DeviceToken { get; set; } = "";
    public string DeviceId { get; set; } = "";
    public string ConsentAt { get; set; } = "";
    public int ScreenshotIntervalSec { get; set; } = 600;
    public bool Paused { get; set; }

    public static string Dir =>
        Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData), "PulseDesk");

    public static string FilePath => Path.Combine(Dir, "agent.json");
    public static string LogPath => Path.Combine(Dir, "agent.log");

    public static Settings Load()
    {
        try
        {
            if (File.Exists(FilePath))
                return JsonSerializer.Deserialize<Settings>(File.ReadAllText(FilePath), AgentJsonContext.Default.Settings) ?? new Settings();
        }
        catch { }
        return new Settings();
    }

    public void Save()
    {
        Directory.CreateDirectory(Dir);
        File.WriteAllText(FilePath, JsonSerializer.Serialize(this, AgentJsonContext.Default.Settings));
    }

    public static void Log(string message)
    {
        try
        {
            Directory.CreateDirectory(Dir);
            File.AppendAllText(LogPath, $"{DateTime.Now:yyyy-MM-dd HH:mm:ss}  {message}{Environment.NewLine}");
        }
        catch { }
    }
}

/// <summary>Reads the enrollment block that the server appended to this exe.</summary>
public static class EmbeddedConfig
{
    public sealed class Conf
    {
        public string code { get; set; } = "";
        public string server { get; set; } = "";
        // New builds carry a second free Cloudflare hostname. If a Windows 11 laptop (or its
        // antivirus / DNS filter) blocks one hostname, enrollment falls back to the other.
        public string[] servers { get; set; } = Array.Empty<string>();
    }

    /// <summary>
    /// Ordered, de-duplicated list of public endpoints to try. The two hardcoded hosts are a
    /// safety net for setups generated by older server builds that only embed "server".
    /// Keeping every endpoint on Cloudflare :443 means the employee firewall only ever sees
    /// ordinary HTTPS traffic to a CDN - no direct Tailscale/ts.net connection from the laptop.
    /// </summary>
    public static IReadOnlyList<string> Endpoints(Conf? c)
    {
        var list = new List<string>();
        void Add(string? u)
        {
            if (string.IsNullOrWhiteSpace(u)) return;
            var v = u.Trim().TrimEnd('/');
            if (!list.Any(x => x.Equals(v, StringComparison.OrdinalIgnoreCase))) list.Add(v);
        }
        if (c != null) { Add(c.server); foreach (var s in c.servers ?? Array.Empty<string>()) Add(s); }
        Add("https://pulsedesk.pulsedesk-numan.workers.dev");
        Add("https://pdsbackup.pulsedesk-numan.workers.dev");
        return list;
    }

    public static Conf? Read()
    {
        try
        {
            var path = Environment.ProcessPath;
            if (string.IsNullOrEmpty(path) || !File.Exists(path)) return null;

            using var fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite);
            int take = (int)Math.Min(8192, fs.Length);
            fs.Seek(-take, SeekOrigin.End);
            var buf = new byte[take];
            fs.ReadExactly(buf, 0, take);

            var text = System.Text.Encoding.UTF8.GetString(buf);
            var idx = text.LastIndexOf("PLSDCONF:", StringComparison.Ordinal);
            if (idx < 0) return null;
            var json = text[(idx + "PLSDCONF:".Length)..].Trim('\0', '\r', '\n', ' ');
            return JsonSerializer.Deserialize<Conf>(json, AgentJsonContext.Default.Conf);
        }
        catch { return null; }
    }
}
